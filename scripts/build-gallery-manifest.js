// Walks assets/images/ and assets/video/ and writes assets/js/gallery-media.js,
// a plain `window.GALLERY_MEDIA = [...]` array that gallery.html shuffles and
// paginates client-side. Re-run (`npm run build:gallery`) after adding or
// removing media so the gallery picks it up.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp']);
const VIDEO_EXT = new Set(['.mp4', '.webm', '.mov']);

// Staging/raw folders that aren't meant to surface publicly.
const EXCLUDE_DIRS = new Set([
  path.join(ROOT, 'assets/video/gallery/review')
]);

function walk(dir, kind, list) {
  if (EXCLUDE_DIRS.has(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, kind, list);
    } else {
      const ext = path.extname(entry.name).toLowerCase();
      if ((kind === 'image' && IMAGE_EXT.has(ext)) || (kind === 'video' && VIDEO_EXT.has(ext))) {
        list.push({ type: kind, src: path.relative(ROOT, full).split(path.sep).join('/') });
      }
    }
  }
}

const media = [];
walk(path.join(ROOT, 'assets/images'), 'image', media);
walk(path.join(ROOT, 'assets/video'), 'video', media);

media.sort((a, b) => a.src.localeCompare(b.src));

const out = '// Generated by scripts/build-gallery-manifest.js — do not edit by hand.\n' +
  'window.GALLERY_MEDIA = ' + JSON.stringify(media, null, 2) + ';\n';

fs.writeFileSync(path.join(ROOT, 'assets/js/gallery-media.js'), out);
console.log('Wrote assets/js/gallery-media.js with ' + media.length + ' entries.');
